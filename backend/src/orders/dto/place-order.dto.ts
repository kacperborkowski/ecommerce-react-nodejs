import { Transform, Type } from 'class-transformer';
import {
  IsDefined,
  IsEmail,
  IsIn,
  IsNotEmpty,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
  ValidateNested,
} from 'class-validator';
import {
  DELIVERY_METHOD_IDS,
  PAYMENT_METHOD_IDS,
} from '../checkout-options.js';
import type { DeliveryMethod, PaymentMethod } from '../checkout-options.js';

// Removes spaces around text, so "  Jan " is saved as "Jan" and "   " fails
// @IsNotEmpty
const Trim = () =>
  Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.trim() : value,
  );

export class CustomerDto {
  @Trim()
  @IsEmail()
  @MaxLength(254)
  email!: string;

  @Trim()
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  firstName!: string;

  @Trim()
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  lastName!: string;

  // Digits and spaces, optionally with a leading +: "+48 600 100 200"
  @Trim()
  @Matches(/^\+?[0-9 ]{9,20}$/, {
    message: 'phone must be a valid phone number',
  })
  phone!: string;
}

export class AddressDto {
  @Trim()
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  street!: string;

  // Polish postal code, e.g. 00-950
  @Trim()
  @Matches(/^\d{2}-\d{3}$/, { message: 'postalCode must look like 00-000' })
  postalCode!: string;

  @Trim()
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  city!: string;
}

// Body of POST /api/orders. The products come from the cart (cookie),
// and prices from the database, never from this body.
export class PlaceOrderDto {
  // Generated by the browser once per checkout, see orders table
  @IsUUID()
  idempotencyKey!: string;

  // @ValidateNested checks the fields inside the object, and @Type tells
  // class-transformer which class to use for it
  @IsDefined()
  @ValidateNested()
  @Type(() => CustomerDto)
  customer!: CustomerDto;

  @IsDefined()
  @ValidateNested()
  @Type(() => AddressDto)
  address!: AddressDto;

  @IsIn(DELIVERY_METHOD_IDS)
  deliveryMethod!: DeliveryMethod;

  @IsIn(PAYMENT_METHOD_IDS)
  paymentMethod!: PaymentMethod;
}
